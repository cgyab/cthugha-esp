void init_palettes(void)
{
    gen_royal_purple(LUTfiles[0]);
    gen_fire(LUTfiles[1]);
    gen_ocean(LUTfiles[2]);
    gen_acid(LUTfiles[3]);
    gen_sunset(LUTfiles[4]);
    memcpy(LUTfiles[5], neon_data,     LUTSIZE);  // Neon
    gen_rainbow(LUTfiles[6]);
    memcpy(LUTfiles[7], firestrm_data, LUTSIZE);  // Fire Storm
    memcpy(LUTfiles[8], volcano_data,  LUTSIZE);  // Volcano
    numluts = 9;
}

void fill_lut_buffer(int pal)
{
    if (pal >= 0) {
        curpal = pal % numluts;
        memcpy(LUTbuffer, LUTfiles[curpal], LUTSIZE);
        pal_cycle_offset = 0;
    }
}
